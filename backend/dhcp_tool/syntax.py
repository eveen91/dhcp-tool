"""Bounded, optional ISC syntax checks; never establish Gaia compatibility."""

import math
import os
import re
import selectors
import signal
import subprocess
import time
from dataclasses import dataclass
from pathlib import Path
from tempfile import TemporaryDirectory

from .generator import ConfigurationError

MAX_CONFIG_BYTES = 1024 * 1024
MAX_OUTPUT_BYTES = 8192


@dataclass(frozen=True)
class SyntaxResult:
    status: str
    parser_version: str | None = None
    return_code: int | None = None


class _OutputLimit(Exception):
    pass


def _run(arguments, directory, deadline):
    """Read bounded output and kill the whole process group on timeout or error."""
    with subprocess.Popen(
        arguments,
        cwd=directory,
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        env={"PATH": os.defpath, "LANG": "C", "LC_ALL": "C"},
        shell=False,
        start_new_session=True,
    ) as process:
        output = bytearray()
        try:
            with selectors.DefaultSelector() as selector:
                selector.register(process.stdout, selectors.EVENT_READ)
                while selector.get_map():
                    remaining = deadline - time.monotonic()
                    if remaining <= 0:
                        raise TimeoutError
                    for key, _ in selector.select(remaining):
                        chunk = os.read(key.fileobj.fileno(), 4096)
                        if not chunk:
                            selector.unregister(key.fileobj)
                        else:
                            output.extend(chunk)
                            if len(output) > MAX_OUTPUT_BYTES:
                                raise _OutputLimit
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                raise TimeoutError
            return process.wait(timeout=remaining), bytes(output)
        finally:
            # Also stop descendants holding pipe descriptors or temporary files.
            try:
                os.killpg(process.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
            process.wait()


def check_syntax(content, *, parser_path=None, timeout=5.0, max_bytes=MAX_CONFIG_BYTES):
    """Check generated bytes with a trusted, explicitly configured absolute binary.

    The caller must pass output from the directive-whitelisted generator or a
    trusted reference fixture, never arbitrary user text (which could contain
    includes or executable expressions).
    No parser is auto-discovered from PATH and no configuration bytes are logged.
    """
    if not isinstance(content, bytes) or not content or len(content) > max_bytes:
        raise ConfigurationError("artifact: expected nonempty bytes within size limit")
    if not math.isfinite(timeout) or timeout <= 0:
        raise ValueError("timeout must be finite and positive")
    if parser_path is None:
        return SyntaxResult("parser_unavailable")
    parser = Path(parser_path)
    if not parser.is_absolute():
        raise ValueError("parser_path must be an absolute path")
    if not parser.is_file() or not os.access(parser, os.X_OK):
        return SyntaxResult("parser_unavailable")

    deadline = time.monotonic() + timeout
    version = None
    try:
        with TemporaryDirectory(prefix="dhcp-check-") as directory:
            code, output = _run([str(parser), "--version"], directory, deadline)
            if code != 0:
                return SyntaxResult("parser_error", return_code=code)
            match = re.search(rb"\bisc-dhcpd-[A-Za-z0-9.+_-]{1,64}\b", output)
            if not match:
                return SyntaxResult("parser_error")
            version = match.group().decode("ascii")
            config = Path(directory) / "dhcpd.conf"
            with config.open("xb") as stream:
                config.chmod(0o600)
                stream.write(content)
            lease = Path(directory) / "dhcpd.leases"
            lease.touch(mode=0o600)
            code, _ = _run(
                [
                    str(parser),
                    "-t",
                    "-4",
                    "-cf",
                    str(config),
                    "-lf",
                    str(lease),
                    "-pf",
                    str(Path(directory) / "dhcpd.pid"),
                ],
                directory,
                deadline,
            )
            status = (
                "syntax_checked" if code == 0 else "syntax_error" if code == 1 else "parser_error"
            )
            return SyntaxResult(status, version, code)
    except (TimeoutError, subprocess.TimeoutExpired):
        return SyntaxResult("parser_timeout", version)
    except _OutputLimit:
        return SyntaxResult("parser_error", version)
    except OSError:
        return SyntaxResult("parser_error", version)
